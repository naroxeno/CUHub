const sprite = app.activeSprite;
const image = sprite.layer(0).cel(0).image;
const white = app.pixelColor.rgba(255, 255, 255, 255);
for (let y = 0; y < image.height; y++) {
    for (let x = 0; x < image.width; x++) {
        image.putPixel(x, y, 0);
    }
}
icons.forEach(([name, bitmap], index) => {
    const left = (index % 4) * 12 + 2;
    const top = Math.floor(index / 4) * 12 + 2;
    const rows = bitmap.split("/");
    if (rows.length !== 8 || rows.some(row => row.length !== 8)) throw Error(name);
    rows.forEach((row, y) => {
        for (let x = 0; x < row.length; x++) {
            if (row[x] === "#") image.putPixel(left + x, top + y, white);
        }
    });
});
sprite.layer(0).name = "Cuprum UI icons · 12 px";
sprite.commit();
